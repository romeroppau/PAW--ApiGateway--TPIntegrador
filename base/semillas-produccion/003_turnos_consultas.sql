LEFT JOIN (SELECT consulta_id, SUM(cantidad * precio_unitario) AS subtotal FROM item_producto_consulta GROUP BY consulta_id) ip ON ip.consulta_id = c.id
WHERE c.id BETWEEN 30001 AND 30760
